// Run with: node tools/build-sw.js  — writes sw.js with every app file listed and a fresh VERSION.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const list = d => fs.readdirSync(path.join(root, d)).filter(f => !f.startsWith('.')).map(f => d + '/' + f);
const files = ['./', 'index.html', 'config.js', 'app.js', 'fonts.css', 'manifest.webmanifest', 'data/catalog.js', 'data/counts.js', ...list('icons'), ...list('fonts'), ...list('data/q')];
const version = 'interview-edge-' + new Date().toISOString().replace(/[-:T]/g, '').slice(0, 12);
fs.writeFileSync(path.join(root, 'sw.js'), `// Offline support. Generated by tools/build-sw.js — run it after any change so phones pick up the update.
const VERSION = '${version}';
const FILES = ${JSON.stringify(files, null, 1)};
self.addEventListener('install', e => { e.waitUntil(caches.open(VERSION).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== VERSION).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
// Network first (so new questions show up), falling back to the saved copy when offline.
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(fetch(e.request).then(res => {
    if (res.ok) { const copy = res.clone(); caches.open(VERSION).then(c => c.put(e.request, copy)); }
    return res;
  }).catch(() => caches.match(e.request, { ignoreSearch: true }).then(r => r || (e.request.mode === 'navigate' ? caches.match('index.html') : undefined))));
});
`);
console.log(version, files.length + ' files');
