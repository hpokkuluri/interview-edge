'Describe the Scrum framework.':
`**Why they ask:** foundational knowledge, in current terms.

**Answer:**
"Under the 2020 Scrum Guide there are three accountabilities: the Product Owner, the Developers and the Scrum Master. Five events: the Sprint as the container, Sprint Planning, the Daily Scrum, the Sprint Review and the Retrospective. And three artifacts, each with a commitment: the Product Backlog with the Product Goal, the Sprint Backlog with the Sprint Goal, and the Increment with the Definition of Done."

Tip: 2020 Scrum Guide terms.`,

'What is the purpose of each Scrum event?':
`**Why they ask:** understanding beyond mechanics.

**Answer:**
"Sprint Planning answers why this sprint matters — the sprint goal — what we'll deliver and how. The Daily Scrum is 15 minutes for developers to inspect progress toward the goal and adapt the plan. The Sprint Review inspects the increment with stakeholders and adapts the backlog. The Retrospective improves how the team works. Every event is an inspect-and-adapt point."

Tip: Inspect and adapt.`,

'What is the Definition of Done?':
`**Why they ask:** quality and transparency.

**Answer:**
"A shared quality standard every increment must meet — code reviewed, automated tests passing, documentation updated, deployed to staging. It creates transparency about what 'done' means and prevents hidden work piling up. It differs from acceptance criteria, which are specific to one item; the DoD applies to all of them."

Tip: DoD vs acceptance criteria.`,

'How do you approach estimation?':
`**Why they ask:** planning philosophy.

**Answer:**
"Relative estimation with story points through planning poker, where the real value is the conversation when one person says 3 and another says 13. Or a no-estimates approach with right-sized items and flow metrics. Either way, estimates are for planning, never for measuring performance or comparing teams."

Tip: Don't compare teams' velocity.`,

'Which metrics do you use?':
`**Why they ask:** measuring team health.

**Answer:**
"Velocity for the team's own planning only, sprint goal success, cycle time and throughput, work in progress, escaped defects, team happiness, and predictability. Flow metrics like cycle time tell me more than velocity about how work actually moves."

Tip: Flow metrics.`,

'How do you handle impediments?':
`**Why they ask:** a core Scrum Master duty.

**Answer:**
"Make them visible, empower the team to solve what they can themselves, escalate organizational blockers, track them to resolution, and look at root causes. If the team waits three days for every test environment, I fix the request process, not just today's environment."

Tip: Team first, then escalate.`,

'How do you keep retrospectives effective?':
`**Why they ask:** continuous improvement.

**Answer:**
"Vary formats — start-stop-continue, sailboat, 4Ls — build psychological safety, bring data like cycle time and carryover, and leave with one or two actionable improvements with owners. Then start the next retro by checking whether we did them; otherwise retros become venting sessions."

Tip: Follow through on actions.`,

