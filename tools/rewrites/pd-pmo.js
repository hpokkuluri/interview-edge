'What types of PMO exist?':
`**Why they ask:** PMO design knowledge.

**Answer:**
"Supportive PMOs provide templates and guidance; controlling PMOs ensure compliance with standards; directive PMOs manage projects directly. Above those sit enterprise PMOs covering the whole portfolio, and agile value management offices. I choose by maturity — an organization with no standards needs a supportive PMO first; forcing a controlling model on it just creates resistance."

Tip: Choose based on maturity.`,

'How do you prioritize a portfolio?':
`**Why they ask:** the core PMO decision.

**Answer:**
"Align initiatives to strategic objectives, score them on value, cost, risk and urgency, check capacity and dependencies, balance across run, grow and transform categories, and review in a regular governance forum. Capacity is the constraint people forget — ranking 60 projects is meaningless if we only have people for 35."

Tip: Capacity-constrained.`,

'How do you design project intake?':
`**Why they ask:** demand management.

**Answer:**
"A simple request form, quick triage and sizing, a business case only for larger efforts, consistent scoring criteria, staged approvals, and transparency about every decision. Small requests under, say, $50K or two months go through a light path so the process doesn't become the bottleneck."

Tip: Lightweight for small work.`,

'How do you manage resource capacity?':
`**Why they ask:** a constant PMO challenge.

**Answer:**
"Track demand versus capacity by skill, avoid overallocating key people, plan in quarterly cycles, use a resource management tool, and make trade-offs visible to leaders. If data engineering is booked at 140%, leadership needs to see that and choose what waits."

Tip: Say no transparently.`,

'What portfolio reporting do executives need?':
`**Why they ask:** executive communication.

**Answer:**
"Portfolio health in red, amber and green, spend versus budget, milestone attainment, top risks, resource constraints, benefits realized, and decisions needed — on a concise dashboard. The decisions section is the most important part; everything else supports it."

Tip: Decisions needed.`,

'How do you avoid PMO bureaucracy?':
`**Why they ask:** credibility with delivery teams.

**Answer:**
"Tier governance by project size and risk, automate reporting from the tools teams already use, focus on outcomes, remove templates nobody reads, and ask project teams regularly what's useful. A $30K project shouldn't face the same gates as a $10M ERP program."

Tip: Tiered governance.`,

'How do you standardize delivery across waterfall and agile teams?':
`**Why they ask:** hybrid environments.

**Answer:**
"Standardize governance outcomes — scope, risk, value, milestones — while allowing different methods, with hybrid frameworks and consistent reporting metrics. An agile team reports progress through releases and burn-up; a waterfall team through milestones; both feed the same portfolio view."

Tip: Outcomes over method.`,

'How do you track benefits realization?':
`**Why they ask:** value accountability.

**Answer:**
"Define benefits and owners in the business case, capture baselines before the project starts, track after delivery — often for 6 to 12 months — and report realized benefits to leadership, closing the loop on investment decisions. Benefit owners sit in the business, because project teams disband at go-live."

Tip: Owners outside the project.`,

'Which PMO metrics matter?':
`**Why they ask:** measuring PMO value.

**Answer:**
"On-time and on-budget delivery, value delivered, portfolio throughput, resource utilization, stakeholder satisfaction and forecast accuracy. Value delivered matters most — finishing the wrong projects on time isn't success."

Tip: Value delivered.`,

'How do you develop project managers?':
`**Why they ask:** capability building.

**Answer:**
"A career framework, training and certification support, mentoring, a community of practice where PMs share lessons, and regular feedback. The community of practice did more for consistency in my last PMO than any template."

Tip: Community of practice.`,

