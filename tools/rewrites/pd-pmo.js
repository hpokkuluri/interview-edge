'What is lean portfolio management?':
`**Why they ask:** agile portfolio concepts.

**Answer:**
"A SAFe concept: fund value streams rather than individual projects, use lean business cases, set guardrails for spending, and use participatory budgeting. It gives teams persistent funding while keeping leadership in control of direction."

Tip: Funding value streams.`,

'How do you manage portfolio-level risk?':
`**Why they ask:** aggregate risk view.

**Answer:**
"Aggregate risks across programs and look for systemic ones — the same vendor on six projects, one overloaded architecture team, shared dependencies — and escalate those to leadership, since no single project can fix them."

Tip: Systemic risks.`,

