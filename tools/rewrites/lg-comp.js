'What does the FCPA prohibit?':
`**Why they ask:** core anti-corruption law.

**Answer:**
"The anti-bribery provisions prohibit offering or giving anything of value to foreign officials to obtain or retain business — including through third parties. The accounting provisions require issuers to keep accurate books and records and adequate internal controls, so a disguised payment booked as 'consulting' can violate the FCPA even if no bribe is proven. The UK Bribery Act goes further, covering commercial bribery and a corporate offense for failing to prevent bribery."

Tip: Books and records.`,

