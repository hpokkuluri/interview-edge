'How do you manage strategic vendors?':
`**Why they ask:** vendor spend is huge.

**Answer:**
"Executive relationships with our key partners, clear value expectations, joint roadmaps, competitive tension at renewal time, and an exit strategy for each, so we're never fully locked in. A partner who knows we could leave behaves like a partner."

Tip: Partnership with leverage.`,

'How do you manage technology risk?':
`**Why they ask:** CIOs own technology risk.

**Answer:**
"An enterprise IT risk register covering cyber, resilience, vendors, technical debt, compliance and AI, with owners and mitigations. It's reported regularly to the risk committee and integrated with enterprise risk management, and we test the mitigations — DR and incident response exercises."

Tip: Integrate with enterprise risk management.`,

