'What should I ask in a skip-level?':
`**Why they ask:** a skip-level is your chance to learn what leadership values and to be remembered for good questions.

**Answer:**
Pick two or three of these and ask them in your own words:
"What are the organization's top priorities this year?"
"What do you wish our team did more of?"
"What skills will matter most here in the next two years?"
"What would you want to see from someone ready for the next level?"

Tip: Listen more than you talk, and write down what they say so you can act on it.`,

'How should I prepare for a skip-level?':
`**Why they ask:** preparation decides whether you come across as a contributor or just a name.

**Answer:**
Bring three key updates, each with one number — for example, "we closed the month two days faster." Add one risk with your plan for it, and one idea with its payoff. Tell your manager the meeting is happening so there are no surprises. Stay positive and solution-focused, and never criticize colleagues. Afterwards, send a short thank-you and deliver anything you promised.

Tip: Three updates, one risk, one idea.`,

