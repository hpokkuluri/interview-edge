"What's the status of non-compete agreements?":
`**Why they ask:** current legal landscape.

**Answer:**
"Enforceability varies by state: California bans most non-competes, and many states limit them by salary thresholds or notice requirements. The FTC's nationwide ban was blocked in court and the agency has since moved away from defending it. So I use narrowly tailored covenants where enforceable and rely more on confidentiality and non-solicitation provisions — and I'd check current law before advising."

Tip: State variation.`,

