'When does the UCC apply?':
`**Why they ask:** commercial law basics.

**Answer:**
"Article 2 governs sales of goods, not services, with gap-filler rules on warranties, the battle of the forms in 2-207, and remedies. For mixed contracts, courts use the predominant purpose test."

Tip: Goods vs services.`,

'What is the battle of the forms?':
`**Why they ask:** practical contracting.

**Answer:**
"When parties exchange conflicting terms — our purchase order versus their invoice — UCC 2-207 determines which terms govern. A signed master agreement that controls over PO and invoice terms avoids it."

Tip: Master agreements.`,

