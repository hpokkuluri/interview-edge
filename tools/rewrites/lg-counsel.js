'Why move in-house?':
`**Why they ask:** motivation and realistic expectations.

**Answer:**
"I want to be part of decisions early instead of reviewing them after the fact, work across a wide variety of issues, and see how my advice plays out in the business. I know the trade-offs — I'll be more generalist than specialist, I'll need to be cost-conscious about outside counsel, and speed often matters more than a perfect memo. That's the kind of practice I want."

Tip: Business focus.`,

'How do you give risk-based advice?':
`**Why they ask:** the core skill of in-house lawyering.

**Answer:**
"I identify the legal risk, its likelihood and impact, weigh it against the business benefit, lay out options to mitigate it, and give a clear recommendation. Instead of 'we can't run this promotion,' it's 'this carries moderate risk in three states; if we exclude them or register there, risk is low — I recommend registering.'"

Tip: Options and recommendation.`,

'What are key provisions you review in commercial contracts?':
`**Why they ask:** contract fluency.

**Answer:**
"Scope and deliverables, pricing and payment, term and termination, warranties, indemnification, limitation of liability, IP ownership and licensing, confidentiality, data protection, insurance, governing law and dispute resolution. Limitation of liability and indemnity are where most of the real risk allocation happens, so I spend the most time there."

Tip: LoL and indemnity.`,

'How do you negotiate limitation of liability?':
`**Why they ask:** risk allocation skill.

**Answer:**
"The typical starting point is a cap at fees paid in the prior 12 months and a mutual exclusion of consequential damages, with carve-outs for indemnification, confidentiality and data breaches, gross negligence and willful misconduct. For a $200,000-a-year vendor holding sensitive customer data, a 12-month cap of $200,000 is too low for a breach, so I'd push for a separate super-cap for data breaches."

Tip: Carve-outs.`,

'What should indemnification cover?':
`**Why they ask:** contract risk.

**Answer:**
"Third-party claims arising from IP infringement, violations of law, bodily injury and property damage, data breaches or negligence — with procedures for prompt notice, who controls the defense, settlement consent and any limits."

Tip: Third-party claims.`,

'How do you scale contract review?':
`**Why they ask:** efficiency.

**Answer:**
"Strong templates, negotiation playbooks with pre-approved fallback positions so contract managers can negotiate without me, self-service for low-risk agreements like standard NDAs, a CLM tool, and AI review assistance. That frees lawyers for high-value deals."

Tip: Playbooks.`,

