'How do you handle an employee complaint?':
`**Why they ask:** employee relations fundamentals.

**Answer:**
"Listen and acknowledge, gather the facts, assess severity and policy implications, involve legal for serious matters like harassment, discrimination or retaliation, investigate impartially, decide and document the outcome, communicate appropriately to the people involved, and actively prevent retaliation. Prompt, fair and documented."

Tip: Prompt, fair, documented.`,

'How do you conduct a workplace investigation?':
`**Why they ask:** a core ER skill.

**Answer:**
"Plan the scope and interview list, explain confidentiality limits, interview the complainant, respondent and witnesses with open questions, collect documents like messages and emails, assess credibility — consistency, corroboration, plausibility, motive — reach findings on the preponderance of evidence, recommend actions, and write a clear report. I don't need certainty, only to decide what's more likely than not."

Tip: Credibility factors.`,

'How do you coach a manager on an underperforming employee?':
`**Why they ask:** practical coaching.

**Answer:**
"Get specific about expectations and gaps — 'closes 6 tickets a day versus the team's 12', not 'not pulling weight'. Check for causes: skills, resources, unclear priorities, personal issues. Then regular feedback, and if needed a performance improvement plan with measurable goals and real support, documented progress, and follow-through on the outcome either way."

Tip: Fair process.`,

'What makes a PIP fair and effective?':
`**Why they ask:** fairness and legal defensibility.

**Answer:**
"Specific, measurable expectations, a realistic timeframe of 30 to 90 days, genuine support and resources, weekly check-ins, documentation, and clear consequences. It should be a real chance to improve — I've seen about a third of employees on well-run PIPs succeed."

Tip: Genuine support.`,

'How do you manage a termination?':
`**Why they ask:** risk and dignity.

**Answer:**
"Confirm documentation and consistency with past decisions, have legal review the risk — protected characteristics, recent complaints, recent leave — plan logistics: final pay timing under state law, benefits, equipment and access removal. Then a brief, respectful meeting with the manager, clear information on next steps, and no debate about the decision."

Tip: Dignity and compliance.`,

