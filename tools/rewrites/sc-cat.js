"What is Porter's five forces and how does it apply to sourcing?":
`**Why they ask:** market analysis drives strategy.

**Answer:**
"The five forces are supplier power, buyer power, the threat of substitutes, the threat of new entrants, and competitive rivalry. In sourcing, they tell me my negotiating leverage. If there are few suppliers and high switching costs, supplier power is high, so I'd focus on partnership or on developing alternatives rather than a hard bid. If there are many suppliers and low switching costs, I can run a competitive event."

Tip: Link the analysis to your strategy choice.`,

'What is total cost of ownership (TCO)?':
`**Why they ask:** shows you look beyond unit price.

**Answer:**
"It's every cost over the life of a purchase — price, freight, duties, inventory carrying, quality costs, installation, training, maintenance, energy, downtime and disposal. For example, printer A costs $2,000 and 8 cents a page; printer B costs $3,000 and 4 cents a page. At 50,000 pages a year for three years, A costs $14,000 in total and B costs $9,000 — so B is $5,000 cheaper even though it's more expensive upfront."

Tip: A worked example shows practical use.`,

'What is should-cost analysis?':
`**Why they ask:** fact-based negotiation.

**Answer:**
"It's building up what a product should cost: materials — weight times price — labor — time times rate — plus overhead, scrap, logistics and a fair margin. If a supplier quotes $12 and my should-cost says $9.50, I can challenge specific elements with facts. It also surfaces cost-reduction ideas. I build these with engineering, because they know the process steps."

Tip: Mention working with engineering.`,

'How do you use commodity indices in contracts?':
`**Why they ask:** managing volatile input costs.

**Answer:**
"I link part of the price to a published index — steel, resin, copper or diesel — with a formula and a review frequency, so price moves fairly in both directions. If resin is 40% of the part cost and the index rises 10%, the price rises 4%. It cuts renegotiation and removes the risk premium suppliers otherwise build in. I often add caps and collars to limit extreme moves."

Tip: Mention caps and collars.`,

'Walk me through running an RFP.':
`**Why they ask:** the core sourcing process.

**Answer:**
"I define requirements and evaluation criteria with stakeholders, then identify and pre-qualify suppliers. The RFP goes out with clear timelines and a standard pricing template so bids are comparable. We hold a Q&A, evaluate responses with a weighted scorecard — say 40% price, 30% capability, 20% service and 10% risk — shortlist, negotiate, run due diligence, award, and plan the implementation and transition."

Tip: Mention a scoring model.`,

