'How do you build an accurate forecast?':
`**Why they ask:** credibility with leadership.

**Answer:**
"Clear stage definitions with evidence-based exit criteria, deal-by-deal inspection, historical conversion rates as a sanity check, commit and best-case categories, and holding reps accountable for accuracy, not just attainment. I got my team's forecast within 5% of actuals by refusing to accept commit deals without a confirmed signature path."

Tip: Inspection.`,

'How do you inspect pipeline health?':
`**Why they ask:** management discipline.

**Answer:**
"Coverage against quota — 3 to 4x — stage distribution, aging deals stuck too long, deal velocity, the quality of next steps, and win rates by stage and by rep. A deal with no next step dated in the next two weeks isn't really progressing."

Tip: Velocity.`,

'What is sales velocity?':
`**Why they ask:** sales math.

**Answer:**
"Number of opportunities times win rate times average deal size, divided by sales cycle length. 50 opportunities at a 25% win rate and $40K average deal, over a 90-day cycle, is $500K divided by 90 — about $5,556 a day. There are four levers, and shortening the cycle is often the easiest."

Tip: Four levers.`,

'How do you handle an underperforming rep?':
`**Why they ask:** performance management.

**Answer:**
"Diagnose first — is it activity, skill or will? Then set clear expectations and metrics, coach intensively on the specific gap, track progress weekly, and make a decision if there's no improvement after a fair period, usually 60 to 90 days."

Tip: Diagnose first.`,

