'Calculate DSCR for a loan.':
`**Why they ask:** a must-know calculation.

**Answer:**
"Take EBITDA of $900,000, subtract unfunded capex of $100,000 and taxes of $150,000 — $650,000 available for debt service. With annual principal and interest of $500,000, DSCR is 1.30x. Many banks require at least 1.20 to 1.25x, so this passes with some cushion; I'd also stress it — a 15% EBITDA drop takes it to about 1.03x."

Tip: Policy minimums.`,

