'What is rough-cut capacity planning?':
`**Why they ask:** feasibility check.

**Answer:**
"It's checking the aggregate plan against the capacity of key resources — critical lines, labor and suppliers — to find overloads before detailed planning. It catches the obvious problems while there's still time to fix them."

Tip: Focus on critical resources.`,

