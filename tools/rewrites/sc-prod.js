'What is lockout/tagout?':
`**Why they ask:** a critical safety rule.

**Answer:**
"It's the OSHA 1910.147 procedure for isolating energy — electrical, hydraulic, pneumatic — before maintenance or clearing a jam. Locks and tags make sure the machine can't start unexpectedly. Each worker applies their own lock and verifies zero energy before touching anything. It's a non-negotiable rule — no shortcuts, even for a quick fix."

Tip: Call it a non-negotiable rule.`,

