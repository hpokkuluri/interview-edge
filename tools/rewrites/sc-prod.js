'What is SMED?':
`**Why they ask:** changeover reduction is high-value.

**Answer:**
"Single-minute exchange of dies — reducing changeover time. You separate internal tasks, done with the machine stopped, from external tasks that can be done while it's running. Then convert as much internal work to external as possible, and streamline both. For example, we cut a changeover from 90 to 25 minutes by pre-staging tools and using quick-release fixtures. Faster changeovers make smaller batches economical."

Tip: Faster changeovers enable smaller batches.`,

