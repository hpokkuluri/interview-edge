'What is moral hazard vs morale hazard?':
`**Why they ask:** underwriting concepts.

**Answer:**
"Moral hazard is dishonesty — like setting a fire for the insurance money. Morale hazard is carelessness because you're insured — like not bothering to lock up. Both shape underwriting decisions."

Tip: Distinction.`,

