'Which marketing metrics matter most?':
`**Why they ask:** business orientation.

**Answer:**
"CAC, ROAS, conversion rate, cost per lead and per acquisition, MQL-to-SQL conversion, pipeline and revenue influenced, LTV, click-through rate and engagement — always tied back to business goals. Leadership cares about pipeline and revenue; clicks only matter if they lead there."

Tip: Revenue metrics.`,

'How do you calculate ROAS and CAC?':
`**Why they ask:** numeracy.

**Answer:**
"ROAS is revenue from ads divided by ad spend — $80K revenue from $20K spend is 4x. CAC is total acquisition cost, marketing plus sales, divided by new customers — $50K across 100 customers is $500. A 4x ROAS can still lose money if margins are thin, so I check it against gross margin."

Tip: Show math.`,

