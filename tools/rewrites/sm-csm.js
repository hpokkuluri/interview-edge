'How do you build a customer health score?':
`**Why they ask:** proactive risk management.

**Answer:**
"Combine product usage — logins, adoption of key features — support ticket trends, NPS or CSAT, engagement like meeting attendance and executive relationships, payment status, and business outcomes. Weight them, then validate against churn history: if accounts scored green churned last year, the weights are wrong. In one model, adoption of two core features predicted renewal far better than login counts."

Tip: Validate against churn.`,

'How do you prevent churn?':
`**Why they ask:** the core CSM outcome.

**Answer:**
"Watch for early signals — usage dropping, a champion leaving, negative feedback, unpaid invoices — reach out proactively, find the root cause, build a recovery plan that demonstrates value, and engage executives on both sides. Churn decided at renewal time was usually lost six months earlier."

Tip: Early signals.`,

'Which CS metrics matter?':
`**Why they ask:** measurement.

**Answer:**
"Gross revenue retention, net revenue retention, logo churn, health scores, adoption, time to value, NPS and CSAT, and expansion revenue. NRR is the headline because it captures both keeping and growing customers."

Tip: NRR.`,

'How do you calculate NRR and GRR?':
`**Why they ask:** financial fluency.

**Answer:**
"NRR is starting ARR plus expansion minus contraction minus churn, divided by starting ARR. GRR is the same without expansion, so it can never exceed 100%. Start with $1 million, add $200K expansion, lose $50K to downgrades and $80K to churn: NRR is $1.07 million over $1 million, 107%; GRR is $870K over $1 million, 87%."

Tip: Show math.`,

