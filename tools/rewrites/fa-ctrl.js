'How would you run a faster, cleaner close?':
`**Why they ask:** close speed and quality are the controller's scorecard.

**Answer:**
"I start with a close calendar that shows every task, owner, dependency and deadline by day. Then I move work into pre-close — accrual estimates, prepaids, depreciation and intercompany cut-off happen before month-end. I automate recurring journals, allocations and reconciliations, and set materiality thresholds so we don't chase small items during close. We hold a short daily stand-up on blockers. And I measure two things: days to close and post-close adjustments. In my last role that took us from a 10-day to a 5-day close over three quarters, with fewer adjustments."

Tip: Speed without quality isn't a win — mention the drop in adjustments too.`,

'Your close keeps slipping because subledgers are late. What do you do?':
`**Why they ask:** controllers have to fix problems owned by other teams.

**Answer:**
"I map the dependencies — which subledger, which task, which person is holding us up. Then I agree hard cut-off times with each owner: AP, AR, inventory, payroll. I show them the impact of a miss on the whole close, and add pre-close checks so problems show up early. If it's a system issue, like cost processing running too long, I work with IT to schedule it earlier. And if one area keeps missing, I take the data to that owner's manager."

Tip: Data on recurring delays turns a complaint into a fix.`,

'How do you decide what is material?':
`**Why they ask:** materiality judgment separates senior accountants from controllers.

**Answer:**
"Materiality is both quantitative and qualitative. On the numbers, common starting points are about 5% of pre-tax income, 0.5 to 1% of revenue, or a share of total assets. So with $40 million of pre-tax income, something around $2 million is a starting point. But qualitative factors can make a small item material — if it affects a debt covenant, involves fraud, turns a loss into a profit, or changes a segment's results. Internally, I set much lower thresholds for close adjustments and flux review than audit materiality."

Tip: Mentioning qualitative materiality shows senior judgment.`,

'How do you design and assess internal controls?':
`**Why they ask:** the controller owns the control environment.

**Answer:**
"I start with risk — for each process, what could go wrong with completeness, accuracy, cut-off or authorization. Then I design controls for each risk: preventive ones like approvals and system restrictions, and detective ones like reconciliations and reviews. Everything goes into a risk and control matrix. We test design and operating effectiveness and fix the gaps. The framework underneath is COSO 2013 — control environment, risk assessment, control activities, information and communication, and monitoring."

Tip: Mention focusing on key controls and why.`,

