'What is the difference between a provision and an accrual?':
`**Why they ask:** a technical check on liability recognition.

**Answer:**
"Both are liabilities recorded before we pay. An accrual is for goods or services we've already received where the amount is fairly certain — like this month's utilities or unbilled consulting hours. A provision is a liability where the timing or amount is uncertain — like warranty costs, a legal claim or restructuring. Under US GAAP it's recorded when it's probable and reasonably estimable; under IFRS, IAS 37, when it's probable and can be reliably estimated."

Tip: One example of each makes the difference clear.`,

'What are contingent liabilities?':
`**Why they ask:** a judgment area auditors focus on.

**Answer:**
"They're possible obligations that depend on a future event — a lawsuit is the classic example. Under US GAAP, ASC 450, we record it if a loss is probable and can be estimated, disclose it if it's reasonably possible, and do nothing if it's remote. IFRS follows similar logic, but 'probable' means more likely than not. So a lawsuit we'll probably lose for about $500,000 gets booked; one we might lose gets a footnote."

Tip: Mention that legal letters during the audit help assess these.`,

'What is the difference between capital and operating expenditures?':
`**Why they ask:** a basic but frequent judgment call in the close.

**Answer:**
"Capex buys or improves long-term assets — equipment, buildings, capitalized software — so it goes on the balance sheet and is depreciated over its useful life. Opex is the day-to-day cost of running the business — salaries, rent, utilities, routine maintenance — and is expensed right away. The split matters because it changes profit, EBITDA and which budget it hits. For example, a $30,000 machine is capex; a $3,000 repair that just keeps it running is opex."

Tip: Add that cloud subscriptions are usually opex, though some implementation costs can be capitalized under ASC 350-40.`,

