'What is CECL and how does it affect bad debt reserves?':
`**Why they ask:** current accounting.

**Answer:**
"CECL — current expected credit loss, under ASC 326 — requires reserving for lifetime expected credit losses on receivables, using historical loss rates adjusted for current conditions and reasonable forecasts. For trade receivables, it's usually done with aging-based loss rates, adjusted if, for example, a recession is expected."

Tip: It's forward-looking.`,

'How do you calculate an allowance for doubtful accounts?':
`**Why they ask:** a key estimate.

**Answer:**
"An aging schedule with a loss rate for each bucket, plus specific reserves for known troubled accounts, adjusted for forward-looking factors. For example: $5 million current at 0.5% is $25,000; $1 million at 31–60 days at 2% is $20,000; $400,000 at 61–90 at 10% is $40,000; $200,000 over 90 at 40% is $80,000. Total: $165,000, before specific reserves."

Tip: Show the calculation.`,

