'Calculate DSCR and interpret.':
`**Why they ask:** a key lending metric.

**Answer:**
"The debt service coverage ratio is cash flow available for debt service divided by total debt service — principal plus interest. Say EBITDA is $1.5 million, and after taxes and capex of $300,000, there's $1.2 million available. With $800,000 of debt service, DSCR is 1.5 times. Lenders often require at least 1.25 times, so this borrower has some cushion."

Tip: Know common covenant thresholds.`,

