'Which operational KPIs do you manage?':
`**Why they ask:** how you measure an operation.

**Answer:**
"A balanced set across six areas: productivity, like units per labor hour; quality, like defect rate and first-pass yield; service, like on-time delivery and SLA attainment; cost, like cost per unit and budget variance; safety, like TRIR; and people, like turnover and engagement. Watching only one — say productivity — usually makes safety or quality slip."

Tip: Balanced scorecard.`,

'How do you manage a P&L?':
`**Why they ask:** financial ownership.

**Answer:**
"Know the revenue and cost drivers cold, run monthly variance analysis, keep a rolling forecast, control discretionary spend, make investment decisions on ROI, and act quickly to close gaps. If labor runs 3% over in month two, I want a fix in month three, not an explanation in month twelve."

Tip: Drivers.`,

'How do you build an operating budget?':
`**Why they ask:** planning discipline.

**Answer:**
"Start from the volume forecast, build a labor model — volume divided by productivity gives hours and headcount — add materials and overhead, list capex needs, and document assumptions agreed with finance so variances can be explained later."

Tip: Labor model.`,

'How do you plan staffing?':
`**Why they ask:** practical workforce planning.

**Answer:**
"Forecast the workload, convert it to labor hours with productivity standards, add allowance for absenteeism and training, and schedule shifts with flexibility through temps, overtime and cross-training. For 10,000 units a week at 25 units an hour, that's 400 hours — 10 full-time people at 40 hours, plus about 10% buffer, so 11."

Tip: Show math.`,

