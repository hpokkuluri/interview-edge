'Explain the hierarchy of controls.':
`**Why they ask:** the core framework of EHS.

**Answer:**
"From most to least effective: elimination — remove the hazard; substitution — replace it with something less hazardous; engineering controls — guarding, ventilation; administrative controls — procedures, training, job rotation; and PPE last. For example, with a solvent hazard, I'd first ask if we can eliminate the cleaning step, then swap to a water-based cleaner, then add local exhaust, and only then rely on respirators."

Tip: PPE is the last line of defense.`,

'How do you calculate TRIR and DART?':
`**Why they ask:** standard safety metrics.

**Answer:**
"TRIR is recordable cases times 200,000, divided by total hours worked. DART uses only days-away, restricted or transferred cases, same formula. The 200,000 represents 100 full-time workers for a year. So 6 recordables over 1.2 million hours gives a TRIR of 1.0."

Tip: Explain the 200,000.`,

'Leading vs lagging indicators?':
`**Why they ask:** modern safety management.

**Answer:**
"Lagging indicators measure outcomes — TRIR, DART, lost time. Leading indicators measure prevention — near-miss reports, safety observations, training completion, corrective action closure and inspections. Lagging tells you you've failed; leading tells you whether you're about to."

Tip: Leading drives improvement.`,

'What are OSHA recordkeeping requirements?':
`**Why they ask:** a compliance basic.

**Answer:**
"We record work-related injuries and illnesses that meet the criteria — medical treatment beyond first aid, days away, restricted work, loss of consciousness or a significant diagnosis — on the OSHA 300 log with a 301 incident report. The 300A summary is posted from February 1 to April 30, and some establishments submit electronically. Fatalities must be reported within 8 hours; inpatient hospitalizations, amputations and eye loss within 24 hours."

Tip: Know the reporting timelines.`,

'How do you investigate an incident?':
`**Why they ask:** systems thinking.

**Answer:**
"Secure the scene and care for the injured. Preserve evidence, interview witnesses promptly, and gather facts — photos and records. Find the root causes with tools like 5 Whys, fishbone or TapRooT. Define corrective actions using the hierarchy of controls, share the lessons, and verify the actions worked. The goal is fixing the system, not blaming a person."

Tip: Systems, not blame.`,

'How do you perform a job hazard analysis?':
`**Why they ask:** a core prevention tool.

**Answer:**
"Break the job into steps, identify the hazards at each step, evaluate the risk, and define controls. I do it with the workers who actually do the job, and update it whenever the process changes. They always spot hazards I'd miss."

Tip: Involve workers.`,

'What is lockout/tagout?':
`**Why they ask:** a life-safety rule.

**Answer:**
"It's OSHA 1910.147, control of hazardous energy. Shut the equipment down, isolate every energy source, apply locks and tags, release stored energy, and verify zero energy before servicing. It needs written procedures for each machine, training, and periodic inspections. The verify step is where most failures happen."

Tip: Verify zero energy.`,

'What are confined space requirements?':
`**Why they ask:** a high-fatality hazard.

**Answer:**
"Under OSHA 1910.146: identify permit-required spaces, use entry permits, test the atmosphere, ventilate, station an attendant, have a rescue plan, train everyone and follow entry procedures. Many confined-space deaths are would-be rescuers, so the rescue plan is critical."

Tip: Rescue plans are critical.`,

