'Compare project delivery methods.':
`**Why they ask:** contract and risk literacy.

**Answer:**
"Design-bid-build separates design and construction and awards to the low bidder — clear competition, but slower and prone to change orders. Design-build puts one entity on the hook for both, so it's faster with fewer disputes, though the owner gives up some design control. CM at risk brings the contractor in during design to give constructability input and a GMP. IPD shares risk and reward across owner, designer and builder — great collaboration, but it needs mature partners."

Tip: Pros and cons.`,

'Lump sum vs cost-plus vs GMP?':
`**Why they ask:** risk allocation.

**Answer:**
"Lump sum is a fixed price, so the contractor carries cost risk and the owner needs complete drawings. Cost-plus has the owner pay actual costs plus a fee — flexible, but the owner carries the risk. GMP is cost-plus with a ceiling: if costs come in at $9.4 million on a $10 million GMP, the $600,000 savings is often split, say 50/50, while overruns above the GMP are the contractor's."

Tip: Risk allocation.`,

'How do you build and manage a construction schedule?':
`**Why they ask:** a core PM skill.

**Answer:**
"A CPM schedule in Primavera P6 or MS Project with activities, durations, logic ties and resources, so I know the critical path. I update it at least monthly, and with the superintendent run three-week look-aheads with subs every week — that's where the schedule actually gets managed. Delays get analyzed against the baseline right away."

Tip: Look-aheads.`,

'How do you handle schedule delays?':
`**Why they ask:** delay management and contractual awareness.

**Answer:**
"Identify the cause and whether it hits the critical path, give written notice within the contract deadline — often 7 to 21 days, and missing it can waive the claim — develop recovery options like resequencing, overtime or added crews, document everything for potential time extension requests, and communicate openly with the owner."

Tip: Contract notices.`,

