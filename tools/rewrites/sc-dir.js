'What is the difference between OTIF and fill rate?':
`**Why they ask:** definitions matter in contracts.

**Answer:**
"Fill rate measures quantity shipped against quantity ordered. OTIF requires each order to be both complete and on time against the customer's requested date. OTIF is stricter and closer to what the customer experiences — you can have 98% fill rate and 85% OTIF. Retailers often fine suppliers on OTIF."

Tip: Definitions matter in customer contracts.`,

