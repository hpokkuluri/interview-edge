'What is the cash-to-cash cycle?':
`**Why they ask:** links supply chain to finance.

**Answer:**
"It's days inventory outstanding plus days sales outstanding minus days payables outstanding — how long cash is tied up in operations. With 60 days of inventory, 45 of receivables and 50 of payables, it's 55 days. Supply chain owns the biggest piece: cutting inventory by 10 days on $100 million of COGS frees about $2.7 million of cash."

Tip: Link it to the CFO's priorities.`,

