'What are the principles of ICH-GCP?':
`**Why they ask:** the foundation of clinical research.

**Answer:**
"Protect the rights, safety and wellbeing of subjects; run scientifically sound protocols; get IRB or IEC approval; obtain informed consent; use qualified investigators; record data accurately; protect confidentiality; handle investigational product under GMP; and maintain quality systems. The updated ICH E6(R3) puts more emphasis on risk-based, proportionate approaches — focusing effort on what matters most to subject safety and data reliability."

Tip: E6(R3).`,

'What types of monitoring visits are there?':
`**Why they ask:** role basics.

**Answer:**
"A site qualification or selection visit to check the site can do the study; a site initiation visit to train staff and confirm readiness; interim monitoring visits during the study; and a close-out visit at the end — plus remote monitoring between visits."

Tip: Purpose of each.`,

'What do you check for informed consent?':
`**Why they ask:** the most important subject protection.

**Answer:**
"The correct IRB-approved version, signed and dated by the subject and the person obtaining consent before any study-specific procedure — even a screening blood draw — documentation of the consent discussion in the source, re-consent after amendments, and confirmation the subject received a copy."

Tip: Before procedures.`,

'What is source data verification vs review?':
`**Why they ask:** monitoring method.

**Answer:**
"SDV compares data in the EDC against source documents for accuracy. SDR reviews source for quality, protocol compliance and safety signals — like an AE noted in a clinic note but never entered. Risk-based monitoring focuses SDV on critical data like primary endpoints and eligibility."

Tip: Critical data.`,

'What is ALCOA+?':
`**Why they ask:** data integrity.

**Answer:**
"Attributable, Legible, Contemporaneous, Original, Accurate — plus Complete, Consistent, Enduring and Available. A vital sign written on a paper towel and transcribed later fails 'original' and 'contemporaneous'."

Tip: Data integrity.`,

'What are AEs and SAEs?':
`**Why they ask:** safety reporting.

**Answer:**
"An adverse event is any untoward medical occurrence in a subject, related to the drug or not. It's serious if it results in death, is life-threatening, requires or prolongs hospitalization, causes significant disability, is a congenital anomaly, or is an important medical event. Sites must report SAEs to the sponsor within 24 hours of becoming aware."

Tip: 24-hour reporting.`,

'How do you handle protocol deviations?':
`**Why they ask:** compliance management.

**Answer:**
"Identify and document it, assess the impact on subject safety and data, report it as required — important deviations get escalated — find the root cause, implement corrective actions and retrain site staff."

Tip: Root cause.`,

'What is risk-based monitoring?':
`**Why they ask:** modern monitoring.

**Answer:**
"Focusing monitoring on critical data and processes identified through a risk assessment, using central monitoring and key risk indicators across sites, instead of 100% SDV on every data point."

Tip: Central monitoring.`,

'How do you monitor investigational product?':
`**Why they ask:** IP accountability.

**Answer:**
"Check storage conditions and temperature logs, accountability records for receipt, dispensing and returns, expiry dates, blinding, and reconciliation of counts. A temperature excursion needs immediate quarantine and sponsor assessment before the product is used."

Tip: Temperature excursions.`,

