'Describe clinical trial phases.':
`**Why they ask:** basics.

**Answer:**
"Phase I tests safety and dosing in a small group, often healthy volunteers. Phase II looks at efficacy and side effects in patients. Phase III confirms efficacy at scale against standard of care. Phase IV is post-marketing surveillance."

Tip: Purpose of each.`,

