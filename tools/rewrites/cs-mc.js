"A client's profits are declining. How do you structure it?":
`**Why they ask:** the classic profitability case.

**Answer:**
"Profit is revenue minus costs, so I'd split it there. Revenue is price times volume, which I'd break down by segment, product and channel. Costs split into fixed and variable. I'd compare each piece over time and against competitors to isolate the driver — say revenue is flat but variable cost per unit rose 15% — then dig into root causes, whether market, competition or internal, and recommend actions."

Tip: Segment the data.`,

