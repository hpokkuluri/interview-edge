'How do you handle a total loss vehicle?':
`**Why they ask:** auto claims.

**Answer:**
"Determine actual cash value with valuation tools and local comparables, explain it clearly to the insured, then handle salvage and title transfer. A vehicle is typically a total loss when repair plus salvage exceeds ACV, or past a state threshold like 75%."

Tip: ACV.`,

'Actual cash value vs replacement cost?':
`**Why they ask:** valuation basics.

**Answer:**
"ACV is replacement cost minus depreciation. A roof that costs $20,000 to replace, with a 20-year life and 10 years old, has ACV of $10,000. Replacement cost pays the full $20,000, less deductible, usually after the work is actually done — the policy terms control."

Tip: Policy terms.`,

