// Run with: node tools/merge.js
// Joins the source parts in src/<id>-<n>.js into one data/q/<id>.js per position, then rebuilds counts.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), src = path.join(root, 'src');
const groups = {};
fs.readdirSync(src).filter(f => /^[a-z0-9-]+-\d+\.js$/.test(f)).forEach(f => { const m = f.match(/^(.+)-(\d+)\.js$/); (groups[m[1]] = groups[m[1]] || []).push([+m[2], f]); });
for (const id in groups) {
  const parts = groups[id].sort((a, b) => a[0] - b[0]).map(([, f]) => fs.readFileSync(path.join(src, f), 'utf8').trim());
  fs.writeFileSync(path.join(root, 'data/q', id + '.js'), `// ${id} — generated from src/${id}-*.js by tools/merge.js. Edit the src files, then run: node tools/merge.js\n` + parts.join('\n\n') + '\n');
}
// Module banks: own questions + matching questions from the Oracle role banks.
const vm = require('vm');
const MODS = require('./modules.js');
const ctx = { window: {} }; ctx.QB = ctx.window.QB = {}; vm.createContext(ctx);
fs.readdirSync(path.join(root, 'data/q')).filter(f => /^ora-(?!mod-).+\.js$/.test(f)).forEach(f => vm.runInContext(fs.readFileSync(path.join(root, 'data/q', f), 'utf8'), ctx));
for (const id in MODS) {
  const own = groups[id] ? groups[id].sort((a, b) => a[0] - b[0]).map(([, f]) => fs.readFileSync(path.join(src, f), 'utf8').trim()).join('\n\n') : '';
  const seen = new Set(); const mctx = { window: {} }; mctx.QB = mctx.window.QB = {}; vm.createContext(mctx);
  if (own) vm.runInContext(own, mctx);
  (mctx.QB[id] || []).forEach(x => seen.add(x[1]));
  const extra = [];
  for (const bank in ctx.QB) for (const x of ctx.QB[bank]) if (MODS[id].includes(x[0]) && !seen.has(x[1])) { seen.add(x[1]); const y = x.slice(); if (y[6] && y[6].t) { y[6] = Object.assign({}, y[6]); delete y[6].t; if (!Object.keys(y[6]).length) y.length = 6; } extra.push(y); }
  fs.writeFileSync(path.join(root, 'data/q', id + '.js'), `// ${id} — generated by tools/merge.js: src/${id}-*.js plus matching questions from the Oracle role banks (tools/modules.js).\n` +
    (own ? own + '\n\n' : '') + `QB['${id}'] = (QB['${id}'] || []).concat(${JSON.stringify(extra, null, 0)});\n`);
}
require('./build-counts.js');
