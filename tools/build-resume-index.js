// Run with: node tools/build-resume-index.js  (merge.js runs it too)
// Writes data/resume-index.js: the most distinctive terms of each question bank, used by Resume Match
// to compare a resume with every role on the device (no bank downloads needed for the match).
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.join(__dirname, '..');
const R = require(path.join(root, 'resume.js'));
const ctx = { window: {} }; ctx.QB = ctx.window.QB = {}; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'data/catalog.js'), 'utf8'), ctx);
fs.readdirSync(path.join(root, 'data/q')).filter(f => f.endsWith('.js')).forEach(f => vm.runInContext(fs.readFileSync(path.join(root, 'data/q', f), 'utf8'), ctx));
const META = {};
ctx.window.CATALOG.forEach(fam => fam.positions.forEach(p => {
  const add = (id, blurb, track) => { META[id] = { text: [p.title, track || '', blurb, p.blurb, fam.name, fam.tag].join('. ') }; };
  if (p.tracks) p.tracks.forEach(t => add(t.id, t.blurb, t.label)); else add(p.id, p.blurb);
}));
const ids = Object.keys(ctx.QB).filter(id => id !== 'common' && !id.startsWith('w-') && META[id]);
const TF = {}, DF = new Map();
ids.forEach(id => {
  const m = new Map();
  R.features(META[id].text, m, 6);
  ctx.QB[id].forEach(x => {
    R.features(x[0], m, 3); R.features(x[1], m, 2);
    R.features(String(x[2]).replace(/\*\*(Why they ask|Answer|Tip):?\*\*/gi, ' '), m, 0.5);
  });
  TF[id] = m; m.forEach((v, k) => DF.set(k, (DF.get(k) || 0) + 1));
});
const N = ids.length, KEEP = 70, banks = {};
ids.forEach(id => {
  const sc = [];
  TF[id].forEach((v, k) => { const df = DF.get(k); if (df > N * 0.5 || v < 2.5) return; sc.push([k, Math.log1p(v) * Math.log(N / df)]); });
  sc.sort((a, b) => b[1] - a[1]);
  const top = sc.slice(0, KEEP), mx = top.length ? top[0][1] : 1;
  banks[id] = top.map(([k, w]) => k + ':' + Math.max(1, Math.round(w / mx * 99))).join('|');
});
const out = `// Generated by tools/build-resume-index.js — distinctive terms per question bank for Resume Match. Do not edit.
window.RINDEX = ${JSON.stringify({ n: N, banks })};
`;
fs.writeFileSync(path.join(root, 'data/resume-index.js'), out);
console.log('resume index:', N, 'banks,', (out.length / 1024).toFixed(0) + ' KB');
